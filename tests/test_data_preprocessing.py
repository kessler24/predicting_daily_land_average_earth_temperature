"""
Test suite for the `data_cleaning` function in the data preprocessing script located at `scripts/data_preprocessing.py`.

This script validates the correctness, robustness, and type safety of the
`data_cleaning` preprocessing function used for cleaning the global land average temperature data.

The tests verify:

- Correct output columns and dtypes
- Handling of empty inputs
- Month (1-12), Day (1-31), and Day of Year (1-365) within expected range
- Preservation of unmodified input columns
- Month name column has correct categorical dtype
- Temperature calculation uses anomaly + baseline
- Error handling for invalid input types
- Edge-case behavior for extreme anomaly and year values

Usage
-----
Run all tests and write logs to a directory:

    python tests/test_data_preprocessing.py --logs_path="./logs"

If all tests pass, the `data_preprocessing_tests.log` file will be empty.
"""

import pytest
import pandas as pd
import math
import sys
import os
import logging
import click
sys.path.append(os.path.join(os.path.dirname(__file__), '..'))
from scripts.data_preprocessing import data_cleaning

# call with : 
# python tests/test_data_preprocessing.py --logs_path="logs"

# run all tests
@click.command()
# path to folder to save logs generated by testing, e.g. "../logs". logs will be saved as .log
@click.option('--logs_path', type=str)
def main(logs_path):
    """
    Run the full test suite for the data preprocessing module.

    Parameters
    ----------
    logs_path : str
        Path to the directory where log files should be written. The directory
        will be created if it does not exist.

    Notes
    -----
    This function configures logging, executes all test functions in sequence,
    and prints a confirmation message when all tests pass. Logs are written into
    a file named `data_preprocessing_tests.log` within the provided logs path.
    """
    # Create logs directory to hold validation logs
    if not os.path.exists(logs_path):
        os.makedirs(logs_path)
    
    # Configure logging
    logging.basicConfig(
        filename=f"{logs_path}/data_preprocessing_tests.log",
        filemode="w",
        format="%(asctime)s - %(message)s",
        level=logging.INFO,
    )
    
    test_returns_dataframe()
    test_empty_returns_empty()
    test_columns()
    test_returned_types()
    test_ranges()
    test_columns_not_modified()
    test_month_names()
    test_add_temperature_column()
    test_set_baseline()
    test_incorrect_types_errors()
    test_anomaly_values()
    test_year_values()
    print("All tests passed.")

# General Test Dataframe
raw_test_data = pd.DataFrame({
    "Date Number" : [1880.001, 1880.004, 1880.007],
    "Year" : [1880, 1880, 1880],
    "Month" : [1, 1, 1],
    "Day" : [1, 2, 3],
    "Day of Year" : [1, 2, 3],
    "Anomaly" : [-0.692, -0.592, -0.673]
})

def test_returns_dataframe():
    """
    Test that a non-empty input DataFrame returns a non-empty DataFrame of type `pandas.DataFrame`.
    """
    cleaned_data = data_cleaning(raw_test_data)
    assert isinstance(cleaned_data, pd.DataFrame)
    assert cleaned_data.loc(0) is not None

def test_empty_returns_empty():
    """
    Test that passing an empty DataFrame returns an empty DataFrame.
    """
    # Empty dataframe
    raw_test_data_empty = pd.DataFrame({
        "Date Number" : pd.Series([], dtype="float64"),
        "Year" : pd.Series([], dtype="int64"),
        "Month" : pd.Series([], dtype="int64"),
        "Day" : pd.Series([], dtype="int64"),
        "Day of Year" : pd.Series([], dtype="int64"),
        "Anomaly" : pd.Series([], dtype="float64")
    })
    assert (data_cleaning(raw_test_data_empty)).empty

def test_columns():
    """
    Test that the cleaned DataFrame contains the correct set of columns. Verify all expected columns are present, no additional columns exist, and the columns are in the expected order.
    """
    expected_column_names = [
        "Year",
        "Month",
        "Day",
        "Day of Year",
        "Anomaly",
        "Temperature",
        "Month_Name"
    ]
    assert data_cleaning(raw_test_data).columns.to_list() == expected_column_names

def test_returned_types():
    """
    Test that all returned columns have the expected dtypes. Calendar fields should have integer values, anomaly and temperature fields should have floating-point values, and Month_Name should be categorical with the proper ordering.
    """
    cleaned_data = data_cleaning(raw_test_data)

    expected_types = {
        "Year": "int64",
        "Month": "int64",
        "Day": "int64",
        "Day of Year": "int64",
        "Anomaly": "float64",
        "Temperature": "float64",
        "Month_Name": pd.CategoricalDtype(categories=['January', 'February', 'March', 'April', 'May', 'June',
                  'July', 'August', 'September', 'October', 'November',
                  'December'], ordered=True)
    }

    assert cleaned_data.dtypes.to_dict() == expected_types

def test_ranges():
    """
    Test that Month, Day, and Day of Year fall within valid ranges after cleaning. Valid ranges are: Month: 1–12, Day: 1–31, Day of Year: 1–365. Ensures that no invalid values are introduced in `data_cleaning()`, not that the input data is within valid ranges (this check is performed during data validation).
    """
    # Month, Day, and Day of Year contain values at edges of expected range
    raw_test_data_range_limits = pd.DataFrame({
        "Date Number" : [0, 0, 0],
        "Year" : [0, 0, 0],
        "Month" : [1, 5, 12],
        "Day" : [1, 15, 31],
        "Day of Year" : [1, 60, 365],
        "Anomaly" : [-0.692, -0.592, -0.673]
    })
    
    cleaned_data_range_limits = data_cleaning(raw_test_data_range_limits)
    assert cleaned_data_range_limits["Month"].between(1, 12).all()
    assert cleaned_data_range_limits["Day"].between(1, 31).all()
    assert cleaned_data_range_limits["Day of Year"].between(1, 365).all()

def test_columns_not_modified():
    """
    Test that key input columns (Year, Month, Day, and Day of Year) remain unmodified after cleaning, i.e. match exactly between input and cleaned output.
    """
    cleaned_data = data_cleaning(raw_test_data)
    assert (cleaned_data["Year"]).equals(raw_test_data["Year"])
    assert (cleaned_data["Month"]).equals(raw_test_data["Month"])
    assert (cleaned_data["Day"]).equals(raw_test_data["Day"])
    assert (cleaned_data["Day of Year"]).equals(raw_test_data["Day of Year"])


def test_add_temperature_column():
    """
    Test that the Temperature column is added and computed correctly with the default baseline. The calculation should be: Temperature = Anomaly + baseline.
    """
    cleaned_data = data_cleaning(raw_test_data)
    assert "Temperature" in cleaned_data.columns
    assert math.isclose(cleaned_data["Temperature"][0], 7.898, abs_tol = 0.001)

def test_set_baseline():
    """
    Test that a custom baseline value is computed correctly in the temperature calculation.
    """
    cleaned_data = data_cleaning(raw_test_data, 1.0)
    assert math.isclose(cleaned_data["Temperature"][0], (-0.692 + 1), abs_tol = 0.001)

def test_incorrect_types_errors():
    """
    Test that invalid input dtypes raise `TypeError`, including strings or float inputs for date columns and invalid string inputs for Anomaly column. Note that Anomaly column is cast to float during preprocessing, so integers, floats, or valid numeric strings should not raise an error.
    """
    # Year provided as string
    raw_test_data_string_year = pd.DataFrame({
        "Date Number" : [1],
        "Year" : ["1880"],
        "Month" : [1],
        "Day" : [1],
        "Day of Year" : [1],
        "Anomaly" : [1]
    })

    # Year provided as float
    raw_test_data_float_year = pd.DataFrame({
        "Date Number" : [1],
        "Year" : [1880.5],
        "Month" : [1],
        "Day" : [1],
        "Day of Year" : [1],
        "Anomaly" : [1]
    })

    # Anomaly provided as invalid string
    raw_test_data_string_anomaly = pd.DataFrame({
        "Date Number" : [1],
        "Year" : [1],
        "Month" : [1],
        "Day" : [1],
        "Day of Year" : [1],
        "Anomaly" : ["1,234"]
    })
  
    with pytest.raises(TypeError):
        data_cleaning(raw_test_data_string_year)
        data_cleaning(raw_test_data_float_year)
        data_cleaning(raw_test_data_string_anomaly)

def test_anomaly_types():
    """
    Test that Anomaly values are correctly cast to float when provided
    as integers or numeric strings.
    """

    # Anomaly provided as integers
    df_int = pd.DataFrame({
        "Date Number": [0, 0, 0],
        "Year": [2000, 2000, 2000],
        "Month": [1, 1, 1],
        "Day": [1, 2, 3],
        "Day of Year": [1, 2, 3],
        "Anomaly": [0, 5, -3]
    })
    cleaned_int = data_cleaning(df_int)
    assert cleaned_int["Anomaly"].dtype == "float64"
    assert cleaned_int["Anomaly"].tolist() == [0.0, 5.0, -3.0]

    # Anomaly provided as numeric strings
    df_str = pd.DataFrame({
        "Date Number": [0, 0, 0],
        "Year": [2000, 2000, 2000],
        "Month": [1, 1, 1],
        "Day": [1, 2, 3],
        "Day of Year": [1, 2, 3],
        "Anomaly": ["0.25", "-1.5", "3"]
    })
    cleaned_str = data_cleaning(df_str)
    assert cleaned_str["Anomaly"].dtype == "float64"
    assert cleaned_str["Anomaly"].tolist() == [0.25, -1.5, 3.0]    

def test_anomaly_values():
    """
    Test temperature computation using extreme anomaly values. Check that large positive, large negative, and close to 0 anomalies all produce correct temperature values.
    """
    # Extreme anomaly values
    raw_test_data_anomaly_values = pd.DataFrame({
        "Date Number" : [1880.001, 1880.004, 1880.007],
        "Year" : [1880, 1880, 1880],
        "Month" : [1, 1, 1],
        "Day" : [1, 2, 3],
        "Day of Year" : [1, 2, 3],
        "Anomaly" : [-1000.6543, 1000.444, 0.00000008]
    })

    cleaned_data = data_cleaning(raw_test_data_anomaly_values, 1.0) 
    assert math.isclose(cleaned_data["Temperature"][0], (-1000.6543 + 1.0), abs_tol = 0.001)
    assert math.isclose(cleaned_data["Temperature"][1], (1000.444 + 1.0), abs_tol = 0.001)
    assert math.isclose(cleaned_data["Temperature"][2], (0.00000008 + 1.0), abs_tol = 0.001)


def test_year_values():
    """
    Test that extreme year values are preserved and not altered, including negative years, year zero, and very large years.
    """
    # Extreme year values
    raw_test_data_year_values = pd.DataFrame({
        "Date Number" : [1880.001, 1880.004, 1880.007],
        "Year" : [-2003, 0, 6789543],
        "Month" : [1, 1, 1],
        "Day" : [1, 2, 3],
        "Day of Year" : [1, 2, 3],
        "Anomaly" : [-0.692, -0.592, -0.673]
    })
    cleaned_data = data_cleaning(raw_test_data_year_values, 1.0)
    assert cleaned_data["Year"].equals(raw_test_data_year_values["Year"])

if __name__ == "__main__":
    main()
